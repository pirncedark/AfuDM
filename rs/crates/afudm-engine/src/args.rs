use std::path::Path;

pub(crate) fn arguments(
    secret: &str,
    download_dir: &Path,
    data_dir: &Path,
    port: u16,
) -> Vec<String> {
    vec![
        "--enable-rpc".into(),
        "--rpc-listen-all=false".into(),
        format!("--rpc-listen-port={port}"),
        format!("--rpc-secret={secret}"),
        "--rpc-allow-origin-all=true".into(),
        format!("--dir={}", download_dir.display()),
        "--max-connection-per-server=16".into(),
        "--split=64".into(),
        "--min-split-size=1M".into(),
        "--max-concurrent-downloads=5".into(),
        "--optimize-concurrent-downloads=true".into(),
        "--disk-cache=64M".into(),
        "--file-allocation=falloc".into(),
        "--continue=true".into(),
        "--always-resume=true".into(),
        "--max-tries=10".into(),
        "--retry-wait=3".into(),
        "--timeout=30".into(),
        "--connect-timeout=15".into(),
        "--auto-file-renaming=true".into(),
        "--allow-overwrite=false".into(),
        "--remote-time=true".into(),
        "--user-agent=Mozilla/5.0 (Windows NT 10.0; Win64; x64) AfuDM/1.0".into(),
        "--enable-dht=true".into(),
        "--enable-dht6=false".into(),
        "--dht-listen-port=6881-6899".into(),
        "--listen-port=6891-6900".into(),
        "--enable-peer-exchange=true".into(),
        "--bt-enable-lpd=true".into(),
        "--bt-max-peers=100".into(),
        "--bt-request-peer-speed-limit=50M".into(),
        "--bt-detach-seed-only=true".into(),
        "--seed-ratio=1.0".into(),
        "--seed-time=0".into(),
        "--max-overall-upload-limit=100K".into(),
        "--follow-torrent=true".into(),
        "--bt-save-metadata=false".into(),
        format!(
            "--save-session={}",
            data_dir.join("aria2.session").display()
        ),
        format!("--input-file={}", data_dir.join("aria2.session").display()),
        "--save-session-interval=0".into(),
        "--auto-save-interval=60".into(),
        "--force-save=true".into(),
        format!("--log={}", data_dir.join("aria2.log").display()),
        "--log-level=warn".into(),
        "--console-log-level=error".into(),
        "--quiet=true".into(),
        "--daemon=false".into(),
    ]
}
